def _card(title: str, body: str):
    with st.container(border=True):
        st.markdown(f"#### {title}")
        st.markdown(body)


def _steps(items):
    """번호가 붙은 따라하기 목록. (할 일, 보충설명) 쌍을 받습니다."""
    for i, (todo, note) in enumerate(items, 1):
        c = st.columns([0.5, 11], vertical_alignment="top")
        c[0].markdown(
            f"<div style='background:#2B6CB0;color:#fff;width:26px;height:26px;"
            f"border-radius:50%;text-align:center;font-weight:700;line-height:26px;"
            f"font-size:.85rem'>{i}</div>", unsafe_allow_html=True)
        with c[1]:
            st.markdown(todo)
            if note:
                st.caption(note)


